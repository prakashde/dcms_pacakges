/**
 * Classify a case-insensitive catalog name under DCMS policy; classification alone does not resolve an implementation.
 */
export function formulaJsPolicyStatus(name: string): FormulaJsPolicyStatus {
  const n = name.toUpperCase();
  if (NONDETERMINISTIC_FUNCTIONS.has(n)) return "excluded_nondeterministic";
  if (DATE_SEMANTICS_PENDING_FUNCTIONS.has(n)) return "pending_date_semantics";
  if (SPREADSHEET_CONTEXT_EXCLUDED_FUNCTIONS.has(n))
    return "excluded_spreadsheet_context";
  if (ERROR_VALUE_SEMANTICS_PENDING_FUNCTIONS.has(n))
    return "pending_error_value_semantics";
  if (["HLOOKUP", "VLOOKUP", "LOOKUP"].includes(n))
    return "pending_environment_semantics";
  if (n === "MATCH") return "pending_unsafe_semantics";
  if (n === "SUBSTITUTE") return "dcms_implemented";
  if (DCMS_LAZY_FUNCTIONS.has(n)) return "dcms_implemented";
  return "supported";
}

